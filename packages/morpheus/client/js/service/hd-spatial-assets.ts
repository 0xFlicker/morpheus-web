export function getHDAtlasLayout(url: string, width: number, height: number): HDAtlasLayout | undefined {
  const path = decodeURIComponent(new URL(url, 'https://gamedb.invalid').pathname)
  const prefix = '/HD/spatial-x2-v1/'
  if (!path.startsWith(prefix)) return undefined
  const layout = hdAtlasLayouts[path.slice(prefix.length)]
  if (!layout || width !== layout.frameWidth * layout.cols || height !== layout.frameHeight * layout.rows) {
    throw new Error(`Invalid HD controlled atlas: ${path}`)
  }
  return layout
}
